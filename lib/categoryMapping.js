// 서점이 종합 TOP100에 직접 매기는 원본 분야명(rankings.store_category)을
// 우리가 추적하는 14개 분야(lib/categories.js CATEGORIES)로 정규화하는
// 명시적 매핑 테이블입니다. 문자열 replace가 아니라 "이 서점의 이 원본
// 분야명은 우리 14개 분야 중 정확히 이것과 같다"고 하나씩 확인된 것만
// 올립니다. store_category 원본 데이터 자체는 건드리지 않고, 분야 분포
// 집계(components/Dashboard.jsx categoryDistribution) 시점에만 이 매핑을
// 적용합니다.
//
// 매핑하지 않는 경우(중요): 서점의 원본 분야 하나가 우리 14개 분야 중
// 여러 개에 걸쳐 있어 어느 하나로 단정할 수 없는 경우(예: 예스24/알라딘의
// "소설/시/희곡"은 소설과 에세이/시 양쪽에 걸침, "만화/라이트노벨"은
// 만화와 그 밖의 장르에 걸침)는 절대 올리지 않습니다. 이런 원본 분야명은
// 정규화 없이 원래 이름 그대로 집계되어 CategoryDistributionChart에서
// "그 서점 자체 분류"(*)로 표시됩니다.
//
// 값 출처: 2026-08-25에 각 서점에서 직접 실측해 확인한 값만 올립니다.
// - 교보: 종합 TOP100(saleCmdtClstName) 실측 + 분야별 카테고리 페이지
//   (store.kyobobook.co.kr/bestseller/online/weekly/domestic/{code}) API
//   응답의 saleCmdtClstName 실측.
// - 예스24/알라딘: 종합 TOP100 상세페이지 breadcrumb 실측 + 분야별
//   카테고리 페이지(categories.py의 yes24_category_id/aladin_cid로 이동한
//   실제 상품) breadcrumb 실측.
export const STORE_CATEGORY_MAP = {
  교보문고: {
    "경제/경영": "경제경영",
    "시/에세이": "에세이/시",
    "역사/문화": "역사",
    "정치/사회": "사회과학",
    "예술/대중문화": "예술",
    "컴퓨터/IT": "기술/IT",
    // 소설/인문/자기계발/만화/과학/여행/건강/종교는 교보 원본 분야명이
    // 이미 우리 14개 분야명과 표기가 같아 매핑이 필요 없습니다.
  },
  예스24: {
    "경제 경영": "경제경영",
    "자연과학": "과학",
    "사회 정치": "사회과학",
    "에세이": "에세이/시",
    "IT 모바일": "기술/IT",
    // "건강 취미"는 매핑하지 않습니다: 예스24는 "여행"을 "건강 취미"의
    // 하위 카테고리로 두고 있어서(실측 - "일본 온천 여행"/"발리 여행" 등
    // 순수 여행서도 breadcrumb 2번째 값이 "건강 취미"로 나옴), 건강과
    // 여행 두 분야에 걸쳐 있는 애매한 원본 분류입니다.
    // "소설/시/희곡", "만화/라이트노벨"도 매핑하지 않습니다(위 설명 참고).
  },
  알라딘: {
    "인문학": "인문",
    "예술/대중문화": "예술",
    "건강/취미": "건강",
    "컴퓨터/모바일": "기술/IT",
    "에세이": "에세이/시",
    // 경제경영/자기계발/과학은 알라딘 원본 분야명이 이미 우리 14개
    // 분야명과 표기가 같아 매핑이 필요 없습니다.
    // "소설/시/희곡", "만화/라이트노벨"은 매핑하지 않습니다(위 설명 참고).
  },
};

// bookstore의 원본 store_category 값을 우리 14개 분야명으로 정규화합니다.
// 매핑이 없으면(이미 같은 이름이거나, 14개 밖의 서점 자체 분류이거나,
// 의도적으로 매핑하지 않은 애매한 분류) 원본 이름을 그대로 돌려줍니다.
export function normalizeStoreCategory(bookstore, rawCategory) {
  const trimmed = (rawCategory || "").trim();
  if (!trimmed) return trimmed;
  return STORE_CATEGORY_MAP[bookstore]?.[trimmed] || trimmed;
}
